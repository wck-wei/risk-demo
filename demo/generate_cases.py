"""Regenerate the offline HTML demo data by executing the existing Python engine."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from risk_demo.contracts import Fault
from risk_demo.risk import RiskService


CASES = {
    "credit": [
        ("standard", "标准授信", "客户申请 30,000，分 12 期偿还。", {}, Fault()),
        ("reject", "近期逾期", "客户有近期逾期记录，演示硬规则如何拦截申请。",
         {"customer_id": "CUST2002", "device_id": "DEV-B"}, Fault()),
        ("recover", "收入特征补取", "第一次未取到收入等级，演示引擎如何补取。",
         {}, Fault("missing-once", "income_level")),
        ("review", "收入特征持续缺失", "回补后仍缺少收入等级，演示转人工复核。",
         {}, Fault("missing-always", "income_level")),
    ],
    "order": [
        ("standard", "标准下单", "客户购买一件 4,999 的商品，希望分 6 期付款。", {}, Fault()),
        ("credit", "超过可用额度", "订单金额超过账户快照中的可用额度。",
         {"order_amount": 31000}, Fault()),
        ("timeout", "模型超时", "规则检查通过，欺诈评估未在预算内返回。",
         {}, Fault("model-timeout")),
    ],
    "pricing": [
        ("standard", "标准定价", "客户申请 30,000，基础年利率为 12%。", {}, Fault()),
        ("match", "匹配竞品报价", "符合匹配条件的低风险客户获得更低报价。",
         {"competitor_rate": 0.145}, Fault()),
        ("timeout", "定价模型超时", "定价模型未按时返回，演示何时暂缓报价。",
         {}, Fault("model-timeout")),
    ],
}


def render_cases():
    service = RiskService()
    groups = {}
    for scene, cases in CASES.items():
        sample = json.loads((ROOT / "examples" / f"{scene}.json").read_text(encoding="utf-8"))
        groups[scene] = {}
        for key, title, story, overrides, fault in cases:
            case_request = {**sample, **overrides, "trace_id": f"DEMO-{scene.upper()}-{key.upper()}"}
            response = service.decide(case_request, fault=fault)
            if response["code"] != "OK":
                raise ValueError(f"演示场景 {scene}/{key} 生成失败")
            amount = case_request.get("amount", case_request.get("apply_amount", case_request.get("order_amount")))
            context = {name: case_request[name] for name in ("term_months", "base_rate", "competitor_rate")
                       if name in case_request}
            groups[scene][key] = {"title": title, "story": story, "request": {"amount": amount, **context},
                                  "response": response}
    data = json.dumps(groups, ensure_ascii=False, separators=(",", ":"))
    return f"// Generated by demo/generate_cases.py.\nwindow.demoCases = {data};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Confirm the committed data is current")
    args = parser.parse_args()
    target = Path(__file__).with_name("cases.js")
    content = render_cases()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            parser.exit(1, "演示数据已变化，请重新运行 python3 demo/generate_cases.py\n")
    else:
        target.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
