def prepare_case(scene, key, request):
    config = Configuration.load()
    activity = {}
    if scene == "order" and key == "flow":
        order_scene = {**config.scenes["ORDER_LOAN"], "flow_version": "RCMS_1.1",
                       "rule_stages": ["AML", "FRAUD", "BUSINESS"]}
        config = replace(config, scenes={**config.scenes, "ORDER_LOAN": order_scene})
        config.validate()
        activity["rcms"] = ["当前演示版本将反欺诈节点排在业务规则之前。"]
    service = RiskService(config)
    if scene == "credit" and key == "release":
        code = "CREDIT_SCORE_V1"
        cube = service.magic_cube
        cube.register(code, "2.0", {"threshold": 0.84})
        cube.validate(code, "2.0")
        cube.deploy(code, "2.0")
        activity["registry"] = [
            "新增演示版本 2.0，校验后部署到在线接口。",
            "版本 1.0 保留为已校验版本，可重新部署。",
        ]
    if scene == "order" and key == "report":
        occurred_at = datetime.fromisoformat(request["request_time"]) - timedelta(days=3)
        service.feature_service.report_order(request["customer_id"], "DEMO-REPORTED-ORDER", 9000, occurred_at)
        activity["metadata"] = ["已上报一笔三天前的合成订单，金额 9,000，等待决策时重新计算。"]
    return service, activity


def render_cases():
    groups = {}
    for scene, cases in CASES.items():
        sample = json.loads((ROOT / "examples" / f"{scene}.json").read_text(encoding="utf-8"))
        groups[scene] = {}
        for key, title, story, overrides, fault in cases:
            case_request = {**sample, **overrides, "trace_id": f"DEMO-{scene.upper()}-{key.upper()}"}
            service, activity = prepare_case(scene, key, case_request)
            response = service.decide(case_request, fault=fault)
            if response["code"] != "OK":
                raise ValueError(f"演示场景 {scene}/{key} 生成失败")
            amount = case_request.get("amount", case_request.get("apply_amount", case_request.get("order_amount")))
            context = {name: case_request[name] for name in ("term_months", "base_rate", "competitor_rate")
                       if name in case_request}
            groups[scene][key] = {"title": title, "story": story, "request": {"amount": amount, **context},
                                  "platform_activity": activity,
                                  "metadata_release": service.metadata.release,
                                  "response": response}
    data = json.dumps(groups, ensure_ascii=False, separators=(",", ":"))
    return f"// Generated by demo/generate_cases.py.\nwindow.demoCases = {data};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Confirm the committed data is current")
    args = parser.parse_args()
    target = Path(__file__).with_name("cases.js")
    content = render_cases()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            parser.exit(1, "演示数据已变化，请重新运行 python3 demo/generate_cases.py\n")
    else:
        target.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
